const choice = (label, options, correct) => ({label, options, correct})
const number = (label, unit, correct) => ({label, unit, correct})
const q = (title, parts, keys, fields, tip, explanation) => ({title, parts, keys, fields, tip, explanation})
const direction = (title, parts, keys, options, correct, tip, explanation) =>
  q(title, parts, keys, [choice('请选择一项', options, correct)], tip, explanation)
const evidence = (title, parts, keys, options, correct, grounds, proof, tip, explanation) =>
  q(title, parts, keys, [choice('（1）请选择一项', options, correct), choice('（2）请选择依据', grounds, proof)], tip, explanation)
const amount = (title, parts, keys, label, unit, correct, tip, explanation) =>
  q(title, parts, keys, [number(label, unit, correct)], tip, explanation)
const two = (title, parts, keys, first, second, tip, explanation) =>
  q(title, parts, keys, [number(...first), number(...second)], tip, explanation)

